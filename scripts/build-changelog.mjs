#!/usr/bin/env node
/**
 * Genera src/data/changelog.generated.ts a partir de git tags + git log.
 *
 * Convención: los releases se marcan con tags `vX.Y.Z` (semver). Cada versión
 * agrupa los commits desde el tag anterior hasta ese tag. Los commits posteriores
 * al tag más reciente se emiten como "unreleased".
 *
 * Corre automáticamente como `prebuild` y `predev` (ver package.json).
 */
import { execSync } from 'node:child_process'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(__dirname, '..')
const outFile = resolve(projectRoot, 'src/data/changelog.generated.ts')

function git(cmd) {
  return execSync(`git ${cmd}`, { cwd: projectRoot, encoding: 'utf8' }).trim()
}

function safeGit(cmd, fallback = '') {
  try {
    return git(cmd)
  } catch {
    return fallback
  }
}

/** Parse semver from `vX.Y.Z` tag. Returns null if not semver. */
function parseSemver(tag) {
  const m = tag.match(/^v?(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/)
  if (!m) return null
  return {
    tag,
    version: `${m[1]}.${m[2]}.${m[3]}${m[4] ? `-${m[4]}` : ''}`,
    major: Number(m[1]),
    minor: Number(m[2]),
    patch: Number(m[3]),
    pre: m[4] ?? '',
  }
}

function compareSemverDesc(a, b) {
  if (a.major !== b.major) return b.major - a.major
  if (a.minor !== b.minor) return b.minor - a.minor
  if (a.patch !== b.patch) return b.patch - a.patch
  if (a.pre && !b.pre) return 1
  if (!a.pre && b.pre) return -1
  return b.pre.localeCompare(a.pre)
}

function getTags() {
  const raw = safeGit('tag --list "v*"')
  if (!raw) return []
  return raw
    .split('\n')
    .map(parseSemver)
    .filter(Boolean)
    .sort(compareSemverDesc)
}

function getCommitsBetween(fromRef, toRef) {
  // fromRef exclusive, toRef inclusive. Si fromRef es null, lista todo hasta toRef.
  const range = fromRef ? `${fromRef}..${toRef}` : toRef
  const raw = safeGit(`log ${range} --no-merges --format=%h%x1f%ad%x1f%s --date=short`)
  if (!raw) return []
  return raw.split('\n').map((line) => {
    const [hash, date, subject] = line.split('\x1f')
    return { hash, date, subject }
  })
}

function getTagDate(tag) {
  // Fecha del commit al que apunta el tag (formato ISO short).
  return safeGit(`log -1 --format=%ad --date=short ${tag}`)
}

function buildEntries() {
  const tags = getTags()
  const head = safeGit('rev-parse HEAD')

  /** @type {Array<{ version: string; date: string; tag: string | null; commits: { hash: string; date: string; subject: string }[] }>} */
  const entries = []

  // 1) Unreleased: commits desde el tag más reciente hasta HEAD.
  const newestTag = tags[0]
  const unreleasedFrom = newestTag ? newestTag.tag : null
  const unreleasedCommits = getCommitsBetween(unreleasedFrom, head)
  if (unreleasedCommits.length > 0) {
    entries.push({
      version: 'unreleased',
      date: unreleasedCommits[0]?.date ?? new Date().toISOString().slice(0, 10),
      tag: null,
      commits: unreleasedCommits,
    })
  }

  // 2) Cada tag, en orden semver descendente.
  for (let i = 0; i < tags.length; i++) {
    const tag = tags[i]
    const prev = tags[i + 1] // siguiente más viejo
    const commits = getCommitsBetween(prev?.tag ?? null, tag.tag)
    entries.push({
      version: tag.version,
      date: getTagDate(tag.tag),
      tag: tag.tag,
      commits,
    })
  }

  return entries
}

function emit(entries) {
  const header = `// AUTO-GENERATED by scripts/build-changelog.mjs — DO NOT EDIT BY HAND.
// Regenerate via \`npm run changelog:build\` (also runs as prebuild/predev).

import type { ChangelogEntry } from './changelog-types'

export const generatedChangelog: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)}
`
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, header, 'utf8')
}

const entries = buildEntries()
emit(entries)
console.log(
  `[changelog] ${entries.length} entries (${entries.reduce((n, e) => n + e.commits.length, 0)} commits) → src/data/changelog.generated.ts`,
)
